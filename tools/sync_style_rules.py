#!/usr/bin/env python3
"""Regenerate the vendored de-AI extract and the skill banlist.

The full skill file stays outside the repo (it has personal details). This
tool copies only three sections into
``bookforge/style/vendor/de-ai-revision/rules_extract.md`` and writes
``bookforge/style/generated/deai_skill_banlist.txt`` from that extract.

``--check`` does not need the skill directory. It rebuilds the banlist from
the vendored extract and exits 1 when a generated file or a recorded hash is
stale. That is the CI path.

``--scrub`` is the upstream scrubber. Its bytes are not copied (fiction mode
is a local patch). The tool records the upstream sha256 and prints when it
drifts from the hash already stored in VENDORED.json.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
VENDOR = ROOT / "bookforge" / "style" / "vendor"
EXTRACT = VENDOR / "de-ai-revision" / "rules_extract.md"
SCRUB = VENDOR / "token_scrub" / "scrub.py"
BANLIST = ROOT / "bookforge" / "style" / "generated" / "deai_skill_banlist.txt"
MANIFEST = VENDOR / "VENDORED.json"

SECTIONS = (
    "Banlist (always cut or rephrase)",
    "Packed ambiguous nouns (AI attention tell)",
    "Sentence rules (locked)",
)
BANLIST_HEADER = "GENERATED by tools/sync_style_rules.py, do not edit"
NOTE = (
    "Fiction mode is a local patch on the vendored scrubber: dialogue dashes, "
    "comma joins, and number ranges. Prose mode output stays byte-identical to "
    "upstream. rules_extract.md holds only the Banlist, Packed ambiguous nouns, "
    "and Sentence rules (locked) sections."
)


def sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def sha256_file(path: Path) -> str:
    return sha256_bytes(path.read_bytes())


def extract_sections(skill_text: str) -> str:
    """Return the three named sections, headings included, verbatim."""
    lines = skill_text.splitlines(keepends=True)
    wanted = set(SECTIONS)
    out: list[str] = []
    i = 0
    found = []
    while i < len(lines):
        line = lines[i]
        if line.startswith("## "):
            title = line[3:].strip()
            if title in wanted:
                found.append(title)
                out.append(line if line.endswith("\n") else line + "\n")
                i += 1
                while i < len(lines) and not lines[i].startswith("## "):
                    chunk = lines[i]
                    out.append(chunk if chunk.endswith("\n") else chunk + "\n")
                    i += 1
                continue
        i += 1
    missing = [s for s in SECTIONS if s not in found]
    if missing:
        raise SystemExit(f"skill is missing sections: {', '.join(missing)}")
    # Keep the sections in source order, which is the order they appear.
    text = "".join(out)
    if not text.endswith("\n"):
        text += "\n"
    return text


def banlist_rows(extract: str) -> list[tuple[str, str, str]]:
    """Parse the Banlist 'Words / phrases' line into (kind, term, qualifier)."""
    line = ""
    for raw in extract.splitlines():
        if "Words / phrases:" in raw:
            line = raw
            break
    if not line:
        raise SystemExit("rules extract has no 'Words / phrases' line")
    payload = line.split(":", 1)[1].replace("**", "").strip().rstrip(".")
    entries = [e.strip() for e in payload.split(",") if e.strip()]
    rows = []
    for entry in entries:
        qual = ""
        term = entry
        m = re.fullmatch(r"(.+?)\s*\((figurative|verb)\)", entry)
        if m:
            term, qual = m.group(1).strip(), m.group(2)
        kind = "phrase" if (" " in term or term.endswith("!")) else "word"
        rows.append((kind, term, qual))
    if not rows:
        raise SystemExit("banlist line produced no entries")
    return rows


def format_banlist(rows: list[tuple[str, str, str]]) -> str:
    lines = [BANLIST_HEADER]
    for kind, term, qual in rows:
        lines.append(f"{kind} {term} {qual}".rstrip())
    return "\n".join(lines) + "\n"


def _load_manifest() -> dict:
    if not MANIFEST.exists():
        return {}
    return json.loads(MANIFEST.read_text())


def _write_manifest(data: dict) -> None:
    MANIFEST.parent.mkdir(parents=True, exist_ok=True)
    MANIFEST.write_text(json.dumps(data, indent=2) + "\n")


def _manifest(skill_path: Path | None, scrub_path: Path | None, previous: dict) -> dict:
    prev_sources = previous.get("sources") or {}
    sources = {
        "skill": dict(prev_sources.get("skill") or {}),
        "scrub": dict(prev_sources.get("scrub") or {}),
    }
    if skill_path is not None:
        sources["skill"] = {"path": str(skill_path), "sha256": sha256_file(skill_path)}
    if scrub_path is not None:
        new_hash = sha256_file(scrub_path)
        old = (prev_sources.get("scrub") or {}).get("sha256")
        if old and old != new_hash:
            print(f"upstream scrub DRIFT: {scrub_path} sha256 {new_hash} != recorded {old}", file=sys.stderr)
        elif old == new_hash:
            print(f"upstream scrub: match {new_hash}")
        else:
            print(f"upstream scrub: recorded {new_hash}")
        sources["scrub"] = {"path": str(scrub_path), "sha256": new_hash}
    files = {}
    for path in (SCRUB, EXTRACT):
        rel = str(path.relative_to(ROOT))
        files[rel] = {"sha256": sha256_file(path)}
    date = previous.get("date") or "2026-10-26"
    # Refresh the date only when we actually re-vendor from a source.
    if skill_path is not None or scrub_path is not None:
        date = "2026-10-26"
    return {
        "date": date,
        "note": NOTE,
        "sources": sources,
        "files": files,
    }


def _skill_file(skill_dir: Path) -> Path:
    for name in ("SKILL.md", "de-ai-revision.SKILL.md"):
        p = Path(skill_dir) / name
        if p.exists():
            return p
    raise SystemExit(f"no SKILL.md in {skill_dir}")


def regenerate(skill_dir: Path | None, scrub_path: Path | None) -> None:  # noqa: F811
    previous = _load_manifest()
    skill_file = None
    if skill_dir is not None:
        skill_file = _skill_file(skill_dir)
        EXTRACT.parent.mkdir(parents=True, exist_ok=True)
        EXTRACT.write_text(extract_sections(skill_file.read_text()))
    if not EXTRACT.exists():
        raise SystemExit(f"missing vendored extract: {EXTRACT}")
    BANLIST.parent.mkdir(parents=True, exist_ok=True)
    BANLIST.write_text(format_banlist(banlist_rows(EXTRACT.read_text())))
    if not SCRUB.exists():
        raise SystemExit(f"missing vendored scrubber: {SCRUB}")
    _write_manifest(_manifest(skill_file, Path(scrub_path) if scrub_path else None, previous))


def check() -> int:
    """Exit 1 when the banlist or recorded hashes do not match the vendored files."""
    if not EXTRACT.exists() or not SCRUB.exists() or not MANIFEST.exists() or not BANLIST.exists():
        print("missing vendored or generated file", file=sys.stderr)
        return 1
    expected = format_banlist(banlist_rows(EXTRACT.read_text()))
    actual = BANLIST.read_text()
    stale = False
    if actual != expected:
        print("stale: bookforge/style/generated/deai_skill_banlist.txt", file=sys.stderr)
        stale = True
    manifest = _load_manifest()
    files = manifest.get("files") or {}
    for path in (SCRUB, EXTRACT):
        rel = str(path.relative_to(ROOT))
        got = sha256_file(path)
        recorded = (files.get(rel) or {}).get("sha256")
        if recorded != got:
            print(f"stale hash: {rel} recorded {recorded} actual {got}", file=sys.stderr)
            stale = True
    if not manifest.get("sources", {}).get("scrub", {}).get("sha256"):
        print("VENDORED.json has no upstream scrub sha256", file=sys.stderr)
        stale = True
    if not manifest.get("sources", {}).get("skill", {}).get("sha256"):
        print("VENDORED.json has no upstream skill sha256", file=sys.stderr)
        stale = True
    if not manifest.get("note"):
        print("VENDORED.json has no note", file=sys.stderr)
        stale = True
    return 1 if stale else 0


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description="Sync vendored de-AI rules and report scrub drift.")
    p.add_argument("--skill-dir", type=Path, default=None,
                   help="Directory containing the de-ai-revision SKILL.md (optional; CI omits this)")
    p.add_argument("--scrub", type=Path, default=None, help="Upstream scrub.py, to record its sha256 and report drift")
    p.add_argument("--check", action="store_true",
                   help="Exit 1 if the generated banlist or VENDORED.json hashes are stale. Does not need --skill-dir.")
    args = p.parse_args(argv)
    if args.check:
        if args.skill_dir or args.scrub:
            # Still a check: compare vendored files only. Extra sources are ignored
            # so CI can pass flags without rewriting the tree.
            pass
        return check()
    regenerate(args.skill_dir, args.scrub)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
